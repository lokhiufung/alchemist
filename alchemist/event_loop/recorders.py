from __future__ import annotations

from pathlib import Path

from alchemist.instruments import Instrument


class BarRecorder:
    """Event Loop behaviour 10: one file per instrument per session day."""

    def __init__(self, root: Path, book) -> None: ...
    def record(self, instrument: Instrument, bar: dict) -> None: ...
    def finalize(self) -> None: ...


class TradeRecorder:
    """Event Loop behaviour 10: per-strategy round trips, with currency."""

    def __init__(self, root: Path, gateway, book) -> None: ...
    async def flush(self) -> None: ...
    def finalize(self) -> None: ...


class NullBarRecorder(BarRecorder):
    def __init__(self) -> None: ...
    def record(self, instrument: Instrument, bar: dict) -> None: ...
    def finalize(self) -> None: ...


class NullTradeRecorder(TradeRecorder):
    def __init__(self) -> None: ...
    async def flush(self) -> None: ...
    def finalize(self) -> None: ...
